import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:734,height:900}});
const errors=[],external=[],writes=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:4173'))external.push(r.url());if(r.method()!=='GET')writes.push(r.method());});
await page.addInitScript(()=>localStorage.setItem('karma-language','ar'));
await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
await page.locator('[data-add="1"]').click();
await page.locator('[data-action="cart"]').click();
await page.locator('#shipping-governorate').selectOption('القاهرة');
await expect(page.locator('.gift-line')).toContainText('هدية أول طلب');
await page.locator('#coupon-code').fill('KARMA10');
await page.locator('#coupon-form button').click();
await expect(page.locator('#coupon-error')).toContainText('سجّلي');
await page.locator('[data-grand-total]').evaluate(e=>{if(!e.textContent.includes('٥٣٥'))throw Error('Guest total wrong');});
await page.locator('.member-invite').click();
await page.locator('#member-name').fill('سارة');
await page.locator('#member-email').fill('sara@example.com');
await page.locator('#member-form [type="submit"]').click();
await expect(page.locator('.member-success')).toContainText('سارة');
assert.equal(await page.evaluate(()=>JSON.stringify(localStorage).includes('sara@example.com')),false);
await page.locator('[data-action="use-coupon"]').click();
await expect(page.locator('[data-discount]')).toContainText('٤٨٫٥');
await expect(page.locator('[data-grand-total]')).toContainText('٤٨٦٫٥');
await page.locator('#coupon-code').fill('wrong');
await page.locator('#coupon-form button').click();
await expect(page.locator('#coupon-error')).toContainText('غير صحيح');
await page.locator('#coupon-code').fill(' karma10 ');
await page.locator('#coupon-form button').click();
await expect(page.locator('[data-grand-total]')).toContainText('٤٨٦٫٥');
await page.locator('#delivery-address').fill('شارع النيل، عمارة 12، الدور 3، شقة 8، بجوار الصيدلية');
await page.locator('#contact-phone').fill('01012345678');
await page.locator('[data-action="checkout"]').click();
await expect(page.locator('#info-content')).toContainText('٤٨٦٫٥');
await expect(page.locator('#info-content')).toContainText('عيّنة عناية');
await page.keyboard.press('Escape');
await page.reload({waitUntil:'networkidle'});
await page.locator('[data-action="cart"]').click();
await expect(page.locator('[data-grand-total]')).toContainText('٤٨٦٫٥');
for(let i=0;i<3;i++)await page.locator('[data-cart-qty="1"]').click();
await expect(page.locator('[data-grand-total]')).toContainText('١٬٧٩٦');
await page.locator('[data-action="remove-coupon"]').click();
await expect(page.locator('[data-discount]')).toContainText('٠');
await expect(page.locator('[data-grand-total]')).toContainText('١٬٩٩٠');
await page.locator('#cart-dialog [data-close]').click();
await page.locator('.header-tools [data-action="account"]').click();
await page.locator('[data-action="logout"]').click();
await expect(page.locator('#member-form')).toBeVisible();
assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('karma-member-v1'))),null);
await page.locator('[data-action="sample-member"]').click();
await expect(page.locator('.member-code')).toContainText('KARMA10');
await page.setViewportSize({width:320,height:760});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'qa/member-mobile.png',animations:'disabled'});
await page.locator('[data-action="use-coupon"]').click();
await page.locator('[data-remove]').click();
await expect(page.locator('.gift-line')).toHaveCount(0);
await expect(page.locator('.cart-empty')).toBeVisible();
